type Ctx = {
  lang: Lang;
  dir: "rtl" | "ltr";
  setLang: (l: Lang) => void;
  t: (key: string, vars?: Record<string, string | number>) => string;
};

const I18nContext = createContext<Ctx | null>(null);
const KEY = "mj.lang";

function detect(): Lang {
  if (typeof window === "undefined") return "he";
  const saved = window.localStorage.getItem(KEY) as Lang | null;
  if (saved && DICTS[saved]) return saved;
  const nav = (window.navigator.language || "he").slice(0, 2).toLowerCase();
  const map: Record<string, Lang> = { he: "he", iw: "he", en: "en", es: "es", zh: "zh", hi: "hi", ar: "ar" };
  return map[nav] ?? "en";
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("he");

  useEffect(() => {
    setLangState(detect());
  }, []);

  useEffect(() => {
    if (typeof document === "undefined") return;
    document.documentElement.lang = lang;
    document.documentElement.dir = RTL.includes(lang) ? "rtl" : "ltr";
  }, [lang]);

  const value = useMemo<Ctx>(() => {
    const dict = DICTS[lang];
    return {
      lang,
      dir: RTL.includes(lang) ? "rtl" : "ltr",
      setLang: (l) => {
        setLangState(l);
        try {
          window.localStorage.setItem(KEY, l);
        } catch {
          /* ignore */
        }
      },
      t: (key, vars) => {
        let s = dict[key] ?? he[key] ?? key;
        if (vars)
          for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
        return s;
      },
    };
  }, [lang]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): Ctx {
  const ctx = useContext(I18nContext);
  if (!ctx)
    return {
      lang: "he",
      dir: "rtl",
      setLang: () => {},
      t: (key, vars) => {
        let s = he[key] ?? key;
        if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
        return s;
      },
    };
  return ctx;
}

/** שם ותיאור משחק בשפה הנוכחית (נופל חזרה לעברית) */
export function useGameText(id: string, fallback: { title: string; desc: string }) {
  const { lang } = useI18n();
  return GAME_I18N[lang]?.[id] ?? fallback;
}
